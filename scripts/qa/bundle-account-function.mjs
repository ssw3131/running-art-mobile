// Deterministic single-file artifact for the Supabase Dashboard editor.
// No secret, authentication credential or environment value is included.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const files = ['receipts.ts', 'handler.ts', 'backend.ts', 'index.ts'];
const sources = await Promise.all(files.map(file => readFile(new URL(`../../supabase/functions/delete-account/${file}`, import.meta.url), 'utf8')));
const code = "// Generated by scripts/qa/bundle-account-function.mjs.\nimport { createClient, type SupabaseClient } from 'npm:@supabase/supabase-js@2.117.2';\n" +
  sources.map((source, i) => `\n// Source: ${files[i]}\n${source.replace(/^import .*;\r?\n/gm, '')}`).join('\n');
const directory = new URL('../../.cache/account-hosted-qa/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('delete-account.ts', directory), code);
const result = { files, bytes: Buffer.byteLength(code), sha256: createHash('sha256').update(code).digest('hex') };
await writeFile(new URL('bundle.json', directory), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
