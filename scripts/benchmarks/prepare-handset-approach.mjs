import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {openSqlite} from '../../tests/helpers/sqlite.mjs';
import {createRoadCache,migrateRoadCache} from '../../src/modules/road-data/persistent-cache.ts';
import {mobileRoadCodecs} from '../../src/modules/road-data/mobile-codecs.ts';
import {createRoadLoader} from '../../src/modules/road-data/client.ts';
import {buildGraph,search,toLatLng} from '../../src/modules/route-engine/engine.ts';
import {createApproachPlanner} from '../../src/modules/running/approach.ts';
import {courseFromCalculation} from '../../src/features/route-lab/saved-course.ts';
import {prepareRoute,project,distance} from '../../src/modules/guidance/geometry.ts';
const baseline='6a72e7930e01b5e415bed1eb5ea8bbd90571c5a4';
const directory='src/features/approach-benchmark';
const original=execFileSync('git',['show',`${baseline}:src/modules/running/approach.ts`],{encoding:'utf8'});
fs.writeFileSync(`${directory}/baseline.ts`,`// Frozen planner from ${baseline}; only relative imports relocated.\n`+original.replaceAll("from '../","from '../../modules/"));
const db=openSqlite(':memory:');await migrateRoadCache(db);
const cache=createRoadCache(db,mobileRoadCodecs);
const load=createRoadLoader({getCache:async()=>cache,fetcher:fetch,supply:'national'});
try{
 const origin={lat:37.4979,lng:127.0276},signal=new AbortController().signal;
 const roads=await load(origin,2000,signal),graph=buildGraph(roads.elements,origin,2000);
 const options={version:'0.2',mode:'free-loop',shape:'heart',targetKm:2,radiusKm:2,shapeVersion:'figma-20261024',maxRouteKm:20};
 const result=search(graph,{...options,proximity:'nearby-v1'});
 const course=courseFromCalculation({origin,options,result,liveRoads:true},0),route=prepareRoute(course.route);
 let request,expected;
 for(const node of graph.nodes){
  const [lat,lng]=toLatLng(node,origin),position=[lng,lat];
  const separation=project(route,position,0,route.totalMeters,0).separation;
  if(separation<100||separation>500)continue;
  try{
   const r={course,position,accuracy:5},p=createApproachPlanner(load,async()=>{});
   const plan=await p(r,signal);
   const fixed={...r,targetM:plan.targetM};
   await p(fixed,signal);let timing;
   // 31m along the same source road bypasses the 30m completed-plan reuse bound.
   const moved={...fixed,position:plan.path.find(c=>distance(position,c)>35)};
   if(!moved.position)continue;
   await p(moved,signal,t=>{timing=t;});
   if(timing?.cache!=='graph'||timing.roadMs!==0)continue;
   request={first:fixed,moved};expected={distanceM:(await createApproachPlanner(load,async()=>{})(fixed,signal)).distanceM,manifestHash:roads.cache.manifestHash,release:roads.cache.release};break;
  }catch{}
 }
 if(!request)throw Error('No verified public benchmark request');
 fs.writeFileSync(`${directory}/input.ts`,'// Public Gangnam roads; generated by prepare-handset-approach.mjs.\nexport default '+JSON.stringify({baseline,origin,...request,expected},null,2)+';\n');
 console.log(JSON.stringify({baseline,expected,points:request.first.course.route.length}));
}finally{await cache.close();}
